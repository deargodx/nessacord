// Nessacord: rebrands the app. Based on deargod's GodCord.
// Renderer side (this file):
// - The app's own interface text says "Nessacord" (rewritten in Discord's message tables as they load).
//   References to Discord the company or service (terms, privacy, staff, support, Inc.) stay as they are.
// - "Vencord" in plugin descriptions and setting labels says "Nessacord".
// - Home-button logo, loading-screen logo and the legacy title-bar wordmark (brand.css).
// Main-process side (native.ts): window/taskbar icon, window title, tray tooltip, splash logo,
// Start menu shortcuts (opt-in). Icon assets are generated by tools/make-assets.py.

import { plugins } from "@api/PluginManager";
import { definePluginSettings } from "@api/Settings";
import { disableStyle, enableStyle } from "@api/Styles";
import definePlugin, { OptionType, StartAt } from "@utils/types";

import brandStyle from "./brand.css?managed";

const MOD_NAME = /(?<![\w$])(?:Vencord|Godcord)(?![\w$])/g;

const rebranded: Array<[target: Record<string, any>, key: string, original: string]> = [];

function rebrandText(target: Record<string, any> | undefined | null, key: string) {
    const original = target?.[key];
    if (typeof original !== "string" || !original.includes("cord")) return;

    const text = original.replace(MOD_NAME, "Nessacord");
    if (text === original) return;

    try {
        target![key] = text;
        rebranded.push([target!, key, original]);
    } catch {
        // Read-only property: leave it as it is.
    }
}

function rebrandSettingsDef(def: Record<string, any> | undefined) {
    if (!def) return;

    for (const setting of Object.values(def)) {
        if (setting == null || typeof setting !== "object") continue;

        rebrandText(setting, "description");
        if (Array.isArray(setting.options)) {
            for (const option of setting.options) rebrandText(option, "label");
        }
    }
}

const settings = definePluginSettings({
    brandShortcuts: {
        type: OptionType.BOOLEAN,
        description: "Also rename Discord's Start menu shortcuts to Nessacord, with the Nessacord icon (Windows). Used by Start, search and notification headers.",
        default: false,
        restartNeeded: true
    }
});

export default definePlugin({
    name: "Nessacord",
    description: "Rebrands the app as Nessacord: interface text, logos, window and taskbar icon, window title and tray tooltip.",
    authors: [{ name: "deargod", id: 0n }, { name: "bella", id: 0n }],
    enabledByDefault: true,
    // The interface text, icon, title and tray changes are applied while the app loads.
    requiresRestart: true,
    // Early, so the loading-screen logo is styled before the loading screen appears.
    startAt: StartAt.Init,
    settings,

    patches: [
        {
            // Discord's interface text lives in message tables: {"<hash>":[...message parts...]}.
            // Only literal text is in these tables. Names, server names, message content and other
            // values are filled into placeholders later and never pass through here. URLs are
            // lowercase, so they are untouched too. Applies to every table, including ones that
            // load later (other features, or other languages).
            find: /^\d+\(\i(?:,\i,\i)?\)\{(?:"use strict";)?(?:\i\.r\(\i\);let \i=|\i\.exports=)JSON\.parse\('\{"[\w+/]{6}":\[/,
            all: true,
            noWarn: true,
            replacement: {
                // The app's name only. Discord the company and its services keep their name:
                // "Discord's Terms of Service", "Discord Inc.", "Discord Staff", "Discord Support"...
                // The phone app keeps its name too ("Scan this with the Discord mobile app").
                // All-caps "DISCORD" is never matched: it is the Crisis Text Line keyword
                // ("text DISCORD to 741741") in Discord's safety resources and must stay correct.
                match: /(?<![\w$])Discord(?![\w$])(?!(?:\\?'|’|\\u2019)?s? (?:Terms|Privacy|Community|Staff|Support|Safety|Trust|Developers?|API|Partners?|Security|Official|Server|Inc|[Mm]obile)\b|,? Inc\b)/g,
                replace: "Nessacord"
            }
        }
    ],

    start() {
        enableStyle(brandStyle);

        for (const plugin of Object.values(plugins)) {
            if (plugin.name === "Nessacord") continue;

            rebrandText(plugin, "description");
            rebrandSettingsDef(plugin.settings?.def);
        }
    },

    stop() {
        disableStyle(brandStyle);

        for (const [target, key, original] of rebranded.splice(0)) {
            try {
                target[key] = original;
            } catch { }
        }
    }
});
