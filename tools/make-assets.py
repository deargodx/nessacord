"""Regenerate Nessacord's embedded assets from the sources in assets/.

Run from the repo root:  python -I tools/make-assets.py

Reads:
  assets/brand/nessacordicon.png      the vampire-mouth mark (RGBA)
  assets/theme/lace-source.jpg        lace texture
  assets/theme/photo-source.jpg       chat background photo
  assets/fonts/*.woff2                Cormorant Garamond (SIL OFL), Latin subset, variable weight

Writes:
  src/plugins/nessacord.desktop/iconData.ts      PNG + ICO (base64) for the main process
  src/plugins/nessacord.desktop/brand.css        home button, loading screen and title-bar wordmark
  src/plugins/nessacordTheme/assets.css          @font-face rules and image custom properties
  installer/build/appicon.png, installer/build/windows/icon.ico   installer icon
"""
import base64, io, os
from PIL import Image, ImageFilter, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = lambda *p: os.path.join(ROOT, "assets", *p)
OUT_BRAND = os.path.join(ROOT, "src", "plugins", "nessacord.desktop")
OUT_THEME = os.path.join(ROOT, "src", "plugins", "nessacordTheme")
OUT_INSTALLER = os.path.join(ROOT, "installer", "build")


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def encode(img: Image.Image, fmt: str, **kw) -> bytes:
    buf = io.BytesIO()
    img.save(buf, fmt, **kw)
    return buf.getvalue()


def write(path: str, text: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"  {os.path.relpath(path, ROOT)}  {len(text.encode()) / 1024:.1f} KB")


# ── Brand mark ──────────────────────────────────────────────────────────────
src = Image.open(A("brand", "nessacordicon.png")).convert("RGBA")
art = src.crop(src.getchannel("A").getbbox())
side = int(max(art.size) * 1.06)
square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
square.paste(art, ((side - art.width) // 2, (side - art.height) // 2), art)
mark = lambda px: square.resize((px, px), Image.LANCZOS)

ico_sizes = [(s, s) for s in (16, 20, 24, 32, 40, 48, 64, 96, 128, 256)]
ico = encode(mark(256), "ICO", sizes=ico_sizes)
mark96 = "data:image/webp;base64," + b64(encode(mark(96), "WEBP", quality=92, method=6))
mark256 = "data:image/webp;base64," + b64(encode(mark(256), "WEBP", quality=90, method=6))

# Main process: the .ico is written to Nessacord's data folder at startup (window, taskbar and
# shortcut icon); the WebP is the splash-screen logo.
write(os.path.join(OUT_BRAND, "iconData.ts"),
      "// Generated by tools/make-assets.py. Do not edit by hand.\n"
      f'export const ICON_ICO_BASE64 = "{b64(ico)}";\n'
      f'export const MARK_256_DATA_URI = "{mark256}";\n')

os.makedirs(os.path.join(OUT_INSTALLER, "windows"), exist_ok=True)
with open(os.path.join(OUT_INSTALLER, "windows", "icon.ico"), "wb") as f:
    f.write(ico)
mark(512).save(os.path.join(OUT_INSTALLER, "appicon.png"), optimize=True)

write(os.path.join(OUT_BRAND, "brand.css"), f"""/* Generated by tools/make-assets.py. Do not edit by hand. */

:root {{
    --nessacord-mark: url("{mark96}");
}}

/* Home button: the Nessacord mark instead of Discord's logo. */
[data-guilds-bar-home] [class*="childWrapper_"] svg {{
    display: none;
}}

[data-guilds-bar-home] [class*="childWrapper_"] {{
    background-image: var(--nessacord-mark);
    background-position: center;
    background-repeat: no-repeat;
    background-size: 78%;
}}

/* Windows title-bar wordmark (legacy title bar). */
[class*="wordmarkWindows_"] svg {{
    display: none;
}}

[class*="wordmarkWindows_"]::after {{
    content: "Nessacord";
    font-size: 12px;
    font-weight: 700;
    letter-spacing: 0.02em;
}}

/* Loading screen: the Nessacord mark instead of Discord's animated logo. The video still loads and
   plays (Discord waits for it before revealing the screen); its frames are only moved out of view. */
[data-testid="app-spinner"] {{
    object-position: -10000px 0;
    background-image: url("{mark256}");
    background-position: center;
    background-repeat: no-repeat;
    background-size: 64%;
}}

html:not(.reduce-motion) [data-testid="app-spinner"] {{
    animation: nessacord-logo-pulse 1.4s ease-in-out infinite alternate;
}}

@keyframes nessacord-logo-pulse {{
    from {{ background-size: 56%; }}
    to {{ background-size: 66%; }}
}}
""")

# ── Lace: greyscale, darkened, mirrored into a tile that repeats without seams ─────────
lace = ImageOps.grayscale(Image.open(A("theme", "lace-source.jpg")))
lace = lace.resize((int(lace.width * 0.8), int(lace.height * 0.8)), Image.LANCZOS)
# Map the lace's own range onto near-black, so it reads through the UI without CSS opacity.
lace = ImageOps.autocontrast(lace, cutoff=1).point(lambda v: int(v * 46 / 255))
w, h = lace.size
tile = Image.new("L", (w * 2, h * 2))
tile.paste(lace, (0, 0))
tile.paste(ImageOps.mirror(lace), (w, 0))
tile.paste(ImageOps.flip(lace), (0, h))
tile.paste(ImageOps.flip(ImageOps.mirror(lace)), (w, h))
lace_bytes = encode(tile.convert("RGB"), "WEBP", quality=55, method=6)

# ── Photo: kept greyscale, gently darkened ────────────────────────────────────────────
photo = ImageOps.grayscale(Image.open(A("theme", "photo-source.jpg"))).point(lambda v: int(v * 0.92))
photo_bytes = encode(photo.convert("RGB"), "WEBP", quality=82, method=6)

# ── Fonts ─────────────────────────────────────────────────────────────────────────────
def font(name: str) -> str:
    with open(A("fonts", name), "rb") as f:
        return "data:font/woff2;base64," + b64(f.read())

roman = font("CormorantGaramond-latin.woff2")
italic = font("CormorantGaramond-Italic-latin.woff2")
latin_range = ("U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, "
               "U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD")

write(os.path.join(OUT_THEME, "assets.css"), f"""/* Generated by tools/make-assets.py. Do not edit by hand. */
/* Cormorant Garamond: Copyright 2015 the Cormorant Project Authors. SIL Open Font License 1.1. */

@font-face {{
    font-family: "Nessacord Serif";
    font-style: normal;
    font-weight: 300 700;
    font-display: swap;
    src: url("{roman}") format("woff2");
    unicode-range: {latin_range};
}}

@font-face {{
    font-family: "Nessacord Serif";
    font-style: italic;
    font-weight: 300 700;
    font-display: swap;
    src: url("{italic}") format("woff2");
    unicode-range: {latin_range};
}}

:root {{
    --nessacord-lace: url("data:image/webp;base64,{b64(lace_bytes)}");
    --nessacord-lace-size: {w * 2}px {h * 2}px;
    --nessacord-photo-default: url("data:image/webp;base64,{b64(photo_bytes)}");
    --nessacord-mark: url("{mark96}");
}}
""")

print(f"lace tile {tile.size} {len(lace_bytes) / 1024:.1f} KB, photo {photo.size} {len(photo_bytes) / 1024:.1f} KB, "
      f"ico {len(ico) / 1024:.1f} KB")
